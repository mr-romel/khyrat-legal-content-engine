def _pick(items: tuple[str, ...], topic: str, salt: str, offset: int = 0) -> str:
    value = sum((i + 1) * ord(c) for i, c in enumerate(f"{topic}|{salt}"))
    return items[(value + offset) % len(items)]

def style_index(topic: str, salt: str = "") -> int:
    value = sum((i + 1) * ord(c) for i, c in enumerate(f"{topic}|{salt}"))
    return value % len(STYLES)

def style_instruction(index: int) -> str:
    return STYLES[index % len(STYLES)]

